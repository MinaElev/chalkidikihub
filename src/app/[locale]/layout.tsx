import type { Metadata, Viewport } from 'next';
import { notFound } from 'next/navigation';
import { NextIntlClientProvider, hasLocale } from 'next-intl';
import { getTranslations, setRequestLocale } from 'next-intl/server';
import { Analytics } from '@vercel/analytics/react';
import { SpeedInsights } from '@vercel/speed-insights/next';
import { routing } from '@/i18n/routing';
import { htmlLang, type Locale } from '@/i18n/config';
import { SITE_URL } from '@/lib/seo/site';
import { Header } from '@/components/layout/Header';
import { Footer } from '@/components/layout/Footer';
import { AvailabilityFab } from '@/components/layout/AvailabilityFab';
import { ExitIntentPopup } from '@/components/layout/ExitIntentPopup';
import { BottomNav } from '@/components/layout/BottomNav';
import { ServiceWorker } from '@/components/layout/ServiceWorker';
import { CookieConsent } from '@/components/v3/CookieConsent';
import { Analytics as GoogleAnalytics } from '@/components/v3/Analytics';
import { TrafficCounter } from '@/components/layout/TrafficCounter';
import { JsonLd } from '@/components/seo/JsonLd';
import { organizationLd, websiteLd } from '@/lib/seo/jsonld';
import { BackToTop } from '@/components/v3/BackToTop';
import { LangSuggestBanner } from '@/components/v3/LangSuggestBanner';

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  applicationName: 'ChalkidikiHub',
  manifest: '/manifest.webmanifest',
  // Search Console ownership. v3 proved it with this meta tag; v4 had dropped it, so Google's
  // periodic re-check failed. public/google95f60c8cd7081583.html is the file method, kept as well.
  verification: { google: '23O0hBvOmQHGLCg-_KCo_7HDlwNRkM-OMM7KYlFS8hY' },
  // Logo (sun over waves). /favicon.ico (16/32/48) sits at the root for crawlers and old browsers;
  // generated by scripts/brand/make-icons.mjs.
  icons: {
    icon: [
      { url: '/favicon.ico', sizes: '48x48' },
      { url: '/icons/icon.svg', type: 'image/svg+xml' },
      { url: '/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    ],
    apple: { url: '/apple-touch-icon.png', sizes: '180x180' },
  },
  formatDetection: { telephone: false },
};

export const viewport: Viewport = {
  themeColor: '#0891B2',
  width: 'device-width',
  initialScale: 1,
  // Lets the phone bottom bar sit above the iPhone home indicator (env(safe-area-inset-bottom)).
  viewportFit: 'cover',
};

export default async function LocaleLayout({ children, params }: LayoutProps<'/[locale]'>) {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();
  setRequestLocale(locale);
  const t = await getTranslations({ locale, namespace: 'shell' });
  const avail = await getTranslations({ locale, namespace: 'availabilityRequest' });

  return (
    <html lang={htmlLang[locale as Locale]}>
      <body className="flex min-h-dvh flex-col">
        <a
          href="#main"
          className="sr-only focus:not-sr-only focus:fixed focus:left-3 focus:top-3 focus:z-50 focus:rounded-lg focus:bg-white focus:px-4 focus:py-2 focus:shadow"
        >
          {t('skipToContent')}
        </a>
        {/* Only the strings client components need — not the whole catalogue. */}
        <NextIntlClientProvider messages={null}>
          <Header locale={locale as Locale} />
          <main id="main" className="flex-1">
            {children}
          </main>
          <Footer locale={locale as Locale} />
          <AvailabilityFab label={avail('floating.label')} tooltip={avail('floating.tooltip')} />
          <ExitIntentPopup
            labels={{
              headline: avail('popup.headline'), body: avail('popup.body'), cta: avail('popup.cta'),
              free: avail('popup.free'), dismiss: avail('popup.dismiss'), close: t('close'),
            }}
          />
          <BottomNav
            labels={{ beaches: t('beaches'), places: t('places'), stay: t('stay'), food: t('food'), availability: t('availShort'), menu: t('menu') }}
          />
          <BackToTop />
          <LangSuggestBanner />
          <CookieConsent />
          <GoogleAnalytics />
          <TrafficCounter />
          <ServiceWorker />
        </NextIntlClientProvider>
        <JsonLd data={[organizationLd(), websiteLd(locale as Locale)]} />
        {/* Vercel-only scripts (served from /_vercel/*); off when self-hosted, e.g. on Plesk. */}
        {process.env.VERCEL && <Analytics />}
        {process.env.VERCEL && <SpeedInsights />}
      </body>
    </html>
  );
}
